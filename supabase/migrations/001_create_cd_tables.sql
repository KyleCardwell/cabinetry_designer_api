-- ============================================================
-- UPDATED_AT TRIGGER (reuse pattern from existing tables)
-- ============================================================

CREATE OR REPLACE FUNCTION cd_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER cd_team_defaults_updated_at
  BEFORE UPDATE ON cd_team_defaults
  FOR EACH ROW EXECUTE FUNCTION cd_set_updated_at();

CREATE TRIGGER cd_projects_updated_at
  BEFORE UPDATE ON cd_projects
  FOR EACH ROW EXECUTE FUNCTION cd_set_updated_at();

CREATE TRIGGER cd_rooms_updated_at
  BEFORE UPDATE ON cd_rooms
  FOR EACH ROW EXECUTE FUNCTION cd_set_updated_at();

CREATE TRIGGER cd_walls_updated_at
  BEFORE UPDATE ON cd_walls
  FOR EACH ROW EXECUTE FUNCTION cd_set_updated_at();

CREATE TRIGGER cd_placed_objects_updated_at
  BEFORE UPDATE ON cd_placed_objects
  FOR EACH ROW EXECUTE FUNCTION cd_set_updated_at();
